#!/usr/bin/env python3
"""Garden illustrations: one flat plant in a pot per growth stage (the server's PLANT_STAGES keys).

Generates server/src/vitalocal/web/js/garden.js (plant(stage) → SVG) and the app's vector drawables
res/drawable/plant_<stage>.xml from the same shapes.

    python3 tools/icons/garden.py
"""

from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
WEB_OUT = ROOT / "server/src/vitalocal/web/js/garden.js"
DRAWABLES = ROOT / "android/app/src/main/res/drawable"

POT, RIM, SOIL = "#C2703D", "#A85A2C", "#6B4428"
STEM, DARK, MID, LIGHT = "#0F6E56", "#0F6E56", "#1D9E75", "#5DCAA5"
PETAL, CORE, TRUNK, SEED = "#F0997B", "#FAC775", "#8A5A35", "#9A6A3A"


def circle(cx, cy, r):
    return f"M{cx - r} {cy}a{r} {r} 0 1 0 {2 * r} 0a{r} {r} 0 1 0 {-2 * r} 0Z"


def ellipse(cx, cy, rx, ry):
    return f"M{cx - rx} {cy}a{rx} {ry} 0 1 0 {2 * rx} 0a{rx} {ry} 0 1 0 {-2 * rx} 0Z"


def leaf(x, y, dx, dy):
    """A pointed leaf from (x, y) to (x+dx, y+dy)."""
    mx, my = x + dx / 2, y + dy / 2
    nx, ny = -dy * 0.35, dx * 0.35
    return f"M{x} {y}Q{mx + nx:.1f} {my + ny:.1f} {x + dx} {y + dy}Q{mx - nx:.1f} {my - ny:.1f} {x} {y}Z"


def stem(y0, y1, w=2.4):
    return f"M{32 - w / 2} {y0}h{w}V{y1}h{-w}Z"


POT_SHAPES = [
    (SOIL, "M17 47h30v4H17Z"),
    (POT, "M17 51h30l-3 11H20Z"),
    (RIM, "M14 46h36a1 1 0 0 1 1 1v4a1 1 0 0 1 -1 1H14a1 1 0 0 1 -1 -1v-4a1 1 0 0 1 1 -1Z"),
]

STAGES = {
    "seed": [(SEED, ellipse(32, 44, 4, 3)), (LIGHT, leaf(32, 42, 2, -4))],
    "sprout": [(STEM, stem(46, 36)), (MID, leaf(32, 38, -8, -5)), (LIGHT, leaf(32, 37, 8, -6))],
    "seedling": [
        (STEM, stem(46, 26)),
        (MID, leaf(32, 40, -10, -4)), (MID, leaf(32, 36, 10, -5)),
        (LIGHT, leaf(32, 31, -9, -6)), (LIGHT, leaf(32, 28, 7, -8)),
    ],
    "bush": [
        (DARK, circle(24, 36, 9)), (DARK, circle(40, 36, 9)),
        (MID, circle(32, 30, 11)), (MID, circle(22, 41, 6)), (MID, circle(42, 41, 6)),
        (LIGHT, circle(28, 26, 4)), (LIGHT, circle(38, 33, 3)),
    ],
    "bloom": [
        (STEM, stem(46, 20)),
        (MID, leaf(32, 40, -12, -5)), (MID, leaf(32, 35, 12, -6)), (LIGHT, leaf(32, 29, -9, -5)),
        *[(PETAL, circle(32 + dx, 16 + dy, 5)) for dx, dy in ((0, -6), (6, -2), (4, 5), (-4, 5), (-6, -2))],
        (CORE, circle(32, 16, 4)),
    ],
    "tree": [
        (TRUNK, "M30 46V30h4V46Z"), (TRUNK, "M32 36l6 -5 1.5 1.5 -6 5Z"),
        (DARK, circle(32, 22, 15)), (MID, circle(26, 18, 9)), (MID, circle(38, 24, 9)),
        (LIGHT, circle(24, 14, 4)), (LIGHT, circle(40, 19, 3)),
    ],
    "mighty": [
        (TRUNK, "M30 46V38h4V46Z"),
        (DARK, "M32 22L48 40H16Z"), (MID, "M32 12L45 30H19Z"), (LIGHT, "M32 3L41 18H23Z"),
        (CORE, circle(32, 4, 2)),
    ],
}


def shapes(stage):
    return POT_SHAPES + STAGES[stage]


def main():
    entries = ",\n".join(f'  {k}: {[[c, d] for c, d in shapes(k)]!r}'.replace("'", '"') for k in STAGES)
    WEB_OUT.write_text(f"""// Generated by tools/icons/garden.py. Do not edit by hand.

import {{ s }} from "./dom.js";

const STAGES = {{
{entries},
}};

/** A plant in its pot for a growth stage key (seed … mighty), `size` in px. */
export function plant(stage, {{ size = 56 }} = {{}}) {{
  const shapes = STAGES[stage] || STAGES.seed;
  return s("svg", {{ class: "plant-svg", width: size, height: size, viewBox: "0 0 64 64", "aria-hidden": "true" }},
    shapes.map(([fill, d]) => s("path", {{ fill, d }})));
}}
""")
    for k in STAGES:
        body = "\n".join(f'    <path android:fillColor="{c}" android:pathData="{d}" />' for c, d in shapes(k))
        (DRAWABLES / f"plant_{k}.xml").write_text(
            '<?xml version="1.0" encoding="utf-8"?>\n<!-- generated by tools/icons/garden.py -->\n'
            '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
            '    android:width="64dp" android:height="64dp" android:viewportWidth="64" android:viewportHeight="64">\n'
            f"{body}\n</vector>\n")
    print(f"{len(STAGES)} plants")


if __name__ == "__main__":
    main()
