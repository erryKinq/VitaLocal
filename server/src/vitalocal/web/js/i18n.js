// English wording where the source text is only a unique key ("Light" alone is also the theme)
const EN = { "Light sleep stage": "Light" };

const DICTS = { de: DE, en: EN };

function initial() {
  try {
    const v = localStorage.getItem(KEY);
    if (v && DICTS[v]) return v;
  } catch { /* storage unavailable */ }
  return (navigator.language || "").toLowerCase().startsWith("de") ? "de" : "en";
}

let current = initial();

export const lang = () => current;
export const locale = () => (current === "de" ? "de-DE" : "en-GB");
export const languages = [["de", "Deutsch"], ["en", "English"]];

export function setLang(value) {
  if (!DICTS[value]) return;
  current = value;
  try { localStorage.setItem(KEY, value); } catch { /* ignore */ }
  document.documentElement.lang = value;
}

export function t(s, vars) {
  let out = DICTS[current][s] ?? s;
  if (vars) for (const [k, v] of Object.entries(vars)) out = out.replaceAll(`{${k}}`, v);
  return out;
}

document.documentElement.lang = current;
