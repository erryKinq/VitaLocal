class FoodIn(BaseModel):
    id: uuid.UUID | None = Field(None, description="Client-generated; resubmitting the same id is a no-op")
    name: str = Field(min_length=1, max_length=200)
    brand: str | None = Field(None, max_length=200)
    barcode: str | None = Field(None, max_length=20)
    base_amount: float = Field(100, gt=0, le=100_000)
    base_unit: BaseUnit = "g"
    portions: list[Portion] = Field(default_factory=list, max_length=20)
    nutrients: dict[str, float] = Field(default_factory=dict, description="Per base_amount (see /nutrients)")
    components: list[Component] | None = Field(
        None, max_length=60, description="A dish: its nutrients are computed from these"
    )
    favorite: bool = False
    archived: bool = False

    @model_validator(mode="after")
    def _check(self):
        _check_nutrients(self.nutrients)
        if self.barcode is not None:
            self.barcode = off.normalize_barcode(self.barcode) if self.barcode.strip() else None
        return self


class EntryIn(BaseModel):
    id: uuid.UUID = Field(description="Client-generated; resubmitting the same id is a no-op")
    logged_at: datetime = Field(description="With time zone; the local day follows from it")
    meal_index: int = Field(ge=0, lt=MAX_MEALS)
    food_id: uuid.UUID | None = None
    amount: float | None = Field(None, gt=0, le=100_000, description="In the food's base unit")
    quantity: float = Field(1, gt=0, le=100)
    name: str | None = Field(None, min_length=1, max_length=200, description="Quick entry (no food)")
    nutrients: dict[str, float] | None = Field(None, description="Quick entry: what was eaten in total")
    entered_via: EnteredVia = "webui"
    template_id: uuid.UUID | None = Field(None, description="The meal template the entry was logged from")

    @model_validator(mode="after")
    def _check(self):
        if self.logged_at.tzinfo is None:
            raise ValueError("logged_at must include a timezone")
        if (self.food_id is None) == (self.name is None):
            raise ValueError("give either food_id (+ amount) or name + nutrients")
        if self.name is not None and self.nutrients is None:
            raise ValueError("a quick entry needs nutrients")
        _check_nutrients(self.nutrients)
        return self


