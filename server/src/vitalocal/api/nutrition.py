@router.get("/foods")
def list_foods(
    q: str | None = Query(None, max_length=100, description="Words matched in name, brand or barcode"),
    limit: int = Query(30, ge=1, le=5000),
    updated_since: datetime | None = Query(None, description="Everything changed since (archived too)"),
    include_archived: bool = False,
    include_unused: bool = Query(False, description="Without q: also foods never logged (catalog page)"),
    kind: Literal["dish", "food"] | None = Query(
        None, description="Only dishes (with components) or plain foods"
    ),
    favorites: bool = Query(False, description="Only favorites"),
    conn: Connection = CONN,
) -> list[dict]:
    """The own catalog. With `q`: matches, favorites first, then by use. Without `q`: favorites and
    the most recently used foods (with their last amount). With `updated_since`: changes for a
    client-side cache, oldest first."""
    if updated_since is not None:
        rows = conn.execute(
            text(f"""SELECT {_FOOD_COLS} FROM food WHERE updated_at > :t ORDER BY updated_at, id LIMIT :n"""),
            {"t": updated_since, "n": limit},
        ).all()
        return _foods_out(conn, rows)
    words = [w for w in (q or "").split() if w][:6]
    only_known = "AND (f.favorite OR u.uses IS NOT NULL)"  # no search: favorites and used foods
    where = ["(:arch OR NOT archived)"]
    params: dict = {"arch": include_archived, "n": limit}
    if kind is not None:
        is_dish = "EXISTS (SELECT 1 FROM food_component c WHERE c.food_id = f.id)"
        where.append(is_dish if kind == "dish" else f"NOT {is_dish}")
    if favorites:
        where.append("f.favorite")
    for i, w in enumerate(words):
        where.append(f"(name ILIKE :w{i} OR coalesce(brand, '') ILIKE :w{i} OR barcode = :b{i})")
        params[f"w{i}"] = "%" + w.replace("\\", "\\\\").replace("%", "\\%").replace("_", "\\_") + "%"
        params[f"b{i}"] = w
    rows = conn.execute(
        text(f"""SELECT {", ".join("f." + c.strip() for c in _FOOD_COLS.split(","))}
                 FROM food f
                 LEFT JOIN (SELECT food_id, count(*) AS uses, max(day) AS last_day FROM nutrition_entry
                            WHERE food_id IS NOT NULL GROUP BY food_id) u ON u.food_id = f.id
                 WHERE {" AND ".join(where)}
                       {"" if words or include_unused or kind or favorites else only_known}
                 ORDER BY f.favorite DESC,
                          {"u.uses DESC NULLS LAST, " if words else ""}u.last_day DESC NULLS LAST,
                          u.uses DESC NULLS LAST, lower(f.name)
                 LIMIT :n"""),
        params,
    ).all()
    return _foods_out(conn, rows)


