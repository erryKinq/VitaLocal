def _insert_entry(
    conn: Connection, uid, logged_at: datetime, meal_index: int, item: dict, via: str, template_id=None
) -> bool:
    day = logged_at.astimezone(_tz()).date()
    row = conn.execute(
        text("""INSERT INTO nutrition_entry (uid, source, day, meal_index, meal, logged_at, item_type,
                    food_id,
                    name, brand, amount, unit, quantity, nutrients, entered_via, template_id)
                VALUES (:uid, 'vitalocal', :day, :mi, :meal, :at, :item_type, :food_id, :name, :brand,
                    :amount, :unit, :quantity, CAST(:nutrients AS jsonb), :via, :template_id)
                ON CONFLICT (uid) DO NOTHING RETURNING id"""),
        {
            **item,
            "nutrients": json.dumps(item["nutrients"]),
            "uid": uid,
            "day": day,
            "mi": meal_index,
            "meal": _meal_name(meal_names(conn), meal_index),
            "at": logged_at,
            "via": via,
            "template_id": template_id,
        },
    ).first()
    return row is not None


