@router.get("/body")
def list_body(
    from_: date | None = Query(None, alias="from"),
    to: date | None = Query(None, description="Inclusive local date"),
    metric: BodyMetric | None = None,
    conn: Connection = CONN,
) -> list[dict]:
    """Body measurements, newest first: entered in VitaLocal (editable) and imported (Waistline)."""
    tz = _tz()
    to = to or datetime.now(tz).date()
    from_ = from_ or to - timedelta(days=90)
    params = {
        "s": _local_midnight(from_, tz),
        "e": _local_midnight(to + timedelta(days=1), tz),
        "m": [metric] if metric else list(BODY_METRICS),
    }
    rows = conn.execute(
        text("""SELECT id::text AS id, ts, metric, value, source, true AS editable FROM body_entry
                WHERE metric = ANY(:m) AND ts >= :s AND ts < :e
                UNION ALL
                SELECT NULL, s.ts, s.metric, s.value, coalesce(d.source, 'import'), false FROM sample s
                LEFT JOIN device d ON d.id = s.device_id
                WHERE s.metric = ANY(:m) AND s.ts >= :s AND s.ts < :e
                ORDER BY ts DESC"""),
        params,
    )
    return [dict(r._mapping) for r in rows]


