def _latest_waistline_export(conn: Connection) -> dict | None:
    row = conn.execute(
        text("""SELECT id, outer_artifact_sha256 AS sha, received_at, status, raw_pruned_at
                FROM ingest_batch WHERE source = 'waistline_export'
                ORDER BY received_at DESC, id DESC LIMIT 1""")
    ).first()
    if row is None:
        return None
    return {
        "batch_id": row.id,
        "received_at": row.received_at,
        "status": row.status,
        "sha256": row.sha,
        "available": row.raw_pruned_at is None,
        "age_days": round((datetime.now(UTC) - row.received_at).total_seconds() / 86400, 1),
    }


def _waistline_unit(unit, portion: float) -> tuple[float, str, list[dict]]:
    u = str(unit or "").strip()
    if u.lower() in ("g", "ml"):
        return portion, u.lower(), []
    label = u or "Portion"
    return portion, "portion", [{"label": f"1 {label}"[:60], "amount": 1.0}]


def _waistline_id(kind: str, wid) -> uuid.UUID:
    return uuid.uuid5(_WAISTLINE_NS, f"{kind}:{wid}")


@router.post("/nutrition/waistline-takeover")
def waistline_takeover(conn: Connection = CONN, store: RawStore = Depends(get_store)) -> dict:
    """Replace Waistline: its foods and recipes from the newest export become catalog foods,
    existing entries are linked to them, the meal names are taken over, and from now on Waistline
    exports are refused (its entries become editable). Send a fresh export first."""
    from vitalocal.ingest import service, waistline

    conn.execute(text("SELECT pg_advisory_xact_lock(:k)"), {"k": service.RUN_LOCK})  # no import running
    if (at := waistline_retired_at(conn)) is not None:
        raise HTTPException(409, f"Waistline was already replaced on {at}")
    export = _latest_waistline_export(conn)
    if export is None:
        raise HTTPException(409, "no Waistline export yet: share one from Waistline first")
    if export["status"] not in ("completed", "completed_with_errors"):
        raise HTTPException(
            409, f"the newest Waistline export is {export['status']}; wait until it is imported"
        )
    if not export["available"] or not store.exists(export["sha256"]):
        raise HTTPException(409, "the newest Waistline export is no longer stored; share a fresh one")
    data = json.loads(store.path_for(export["sha256"]).read_bytes())

    def num(v):
        return waistline._num(v)

    foods = recipes = 0
    for f in data.get("foodList") or []:
        if not isinstance(f, dict) or "id" not in f:
            continue
        base, unit, portions = _waistline_unit(f.get("unit"), num(f.get("portion")) or 100.0)
        barcode = str(f.get("barcode") or "").strip()
        try:
            barcode = off.normalize_barcode(barcode) if barcode else None
        except ValueError:
            barcode = None
        nutr = {
            k: v
            for k, v in ((k, num(v)) for k, v in (f.get("nutrition") or {}).items())
            if v is not None and v >= 0
        }
        _, created = store_food(
            conn,
            FoodIn(
                id=_waistline_id("food", f["id"]),
                name=str(f.get("name") or "?")[:200],
                brand=(str(f.get("brand") or "").strip() or None),
                barcode=barcode,
                base_amount=base if base > 0 else 100.0,
                base_unit=unit,
                portions=portions,
                nutrients=nutr,
                archived=bool(f.get("archived") or f.get("hidden")),
            ),
            source="waistline",
            source_ref=f"food:{f['id']}",
        )
        foods += created
    for r in data.get("recipes") or []:
        if not isinstance(r, dict) or "id" not in r:
            continue
        base, unit, portions = _waistline_unit(r.get("unit"), num(r.get("portion")) or 1.0)
        nutr = {
            k: v
            for k, v in ((k, num(v)) for k, v in (r.get("nutrition") or {}).items())
            if v is not None and v >= 0
        }
        rid = _waistline_id("recipe", r["id"])
        _, created = store_food(
            conn,
            FoodIn(
                id=rid,
                name=str(r.get("name") or "?")[:200],
                base_amount=base if base > 0 else 1.0,
                base_unit=unit,
                portions=portions,
                nutrients=nutr,  # Waistline's own totals, not recomputed
                archived=bool(r.get("archived")),
            ),
            source="waistline",
            source_ref=f"recipe:{r['id']}",
        )
        recipes += created
        comps = []
        for i, it in enumerate(r.get("items") or []):
            kind = "recipe" if it.get("type") == "recipe" else "food"
            amount = (num(it.get("portion")) or 0) * (num(it.get("quantity")) or 1.0)
            cid = _waistline_id(kind, it.get("id"))
            if amount > 0 and conn.execute(text("SELECT 1 FROM food WHERE id = :id"), {"id": cid}).first():
                comps.append({"f": rid, "p": i, "c": cid, "a": amount})
        conn.execute(text("DELETE FROM food_component WHERE food_id = :id"), {"id": rid})
        if comps:
            conn.execute(
                text(
                    "INSERT INTO food_component (food_id, position, component_id, amount)"
                    " VALUES (:f, :p, :c, :a)"
                ),
                comps,
            )
    linked = conn.execute(
        text("""UPDATE nutrition_entry e SET food_id = f.id FROM food f
                WHERE e.source = 'waistline' AND e.food_id IS NULL AND f.source = 'waistline'
                  AND f.source_ref = e.item_type || ':' || e.source_item_id""")
    ).rowcount
    raw_names = list(((data.get("settings") or {}).get("diary") or {}).get("meal-names") or [])
    last = max([i for i, n in enumerate(raw_names) if str(n).strip()] + [len(DEFAULT_MEALS) - 1])
    names = [
        (str(raw_names[i]).strip() if i < len(raw_names) else "")
        or (DEFAULT_MEALS[i] if i < len(DEFAULT_MEALS) else f"Mahlzeit {i + 1}")
        for i in range(min(last + 1, MAX_MEALS))
    ]
    from vitalocal.api.templates import import_waistline_meals

    meal_templates = import_waistline_meals(conn, data)
    put_setting(conn, MEALS_KEY, json.dumps(names))
    retired_at = datetime.now(UTC).isoformat()
    put_setting(conn, RETIRED_KEY, json.dumps(retired_at))
    return {
        "retired_at": retired_at,
        "export": {k: export[k] for k in ("batch_id", "received_at")},
        "foods": foods,
        "recipes": recipes,
        "linked_entries": linked,
        "templates": meal_templates,
        "meals": names,
    }
