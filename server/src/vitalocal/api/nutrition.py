def _check_nutrients(v: dict[str, float] | None) -> None:
    for k, x in (v or {}).items():
        if not (0 < len(k) <= 40) or x < 0:
            raise ValueError(f"nutrient {k!r}: name 1–40 characters, value ≥ 0")


