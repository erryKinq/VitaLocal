def _usage(conn: Connection, ids: list) -> dict:
    if not ids:
        return {}
    rows = conn.execute(
        text("""SELECT DISTINCT ON (food_id) food_id,
                       count(*) OVER (PARTITION BY food_id) AS uses,
                       coalesce(logged_at, day::timestamptz) AS last_used, amount, quantity, meal_index
                FROM nutrition_entry WHERE food_id = ANY(:ids)
                ORDER BY food_id, day DESC, created_at DESC, logged_at DESC NULLS LAST"""),
        {"ids": ids},
    )
    return {
        r.food_id: {
            "count": r.uses,
            "last_used": r.last_used,
            "last_amount": r.amount,
            "last_quantity": r.quantity,
            "last_meal_index": r.meal_index,
        }
        for r in rows
    }


def _foods_out(conn: Connection, rows: list) -> list[dict]:
    foods = [dict(r._mapping) for r in rows]
    ids = [f["id"] for f in foods]
    usage = _usage(conn, ids)
    comps: dict = {}
    if ids:
        for c in conn.execute(
            text("""SELECT fc.food_id, fc.component_id, fc.amount, f.name, f.base_unit
                    FROM food_component fc JOIN food f ON f.id = fc.component_id
                    WHERE fc.food_id = ANY(:ids) ORDER BY fc.food_id, fc.position"""),
            {"ids": ids},
        ):
            comps.setdefault(c.food_id, []).append(
                {"food_id": c.component_id, "name": c.name, "amount": c.amount, "unit": c.base_unit}
            )
    for f in foods:
        f["components"] = comps.get(f["id"], [])
        f["usage"] = usage.get(f["id"], {"count": 0, "last_used": None})
    return foods


def get_food(conn: Connection, food_id) -> dict | None:
    row = conn.execute(text(f"SELECT {_FOOD_COLS} FROM food WHERE id = :id"), {"id": food_id}).first()
    return _foods_out(conn, [row])[0] if row else None


def _dish_nutrients(conn: Connection, food_id, components: list[Component]) -> dict[str, float]:
    """Sum of the components' nutrients; a nutrient no component declares stays missing."""
    ids = [c.food_id for c in components]
    if food_id in ids:
        raise HTTPException(422, "a dish cannot contain itself")
    if food_id is not None:
        cyclic = conn.execute(
            text("""WITH RECURSIVE inner_foods(id) AS (
                        SELECT component_id FROM food_component WHERE food_id = ANY(:ids)
                        UNION SELECT fc.component_id FROM food_component fc
                        JOIN inner_foods i ON fc.food_id = i.id)
                    SELECT 1 FROM inner_foods WHERE id = :f LIMIT 1"""),
            {"ids": ids, "f": food_id},
        ).first()
        if cyclic:
            raise HTTPException(422, "a component contains this dish")
    found = {
        r.id: r
        for r in conn.execute(
            text("SELECT id, base_amount, nutrients FROM food WHERE id = ANY(:ids)"), {"ids": ids}
        )
    }
    if missing := [str(i) for i in ids if i not in found]:
        raise HTTPException(422, f"unknown component food: {', '.join(missing)}")
    total: dict[str, float] = {}
    for c in components:
        f = found[c.food_id]
        for k, v in scaled(f.nutrients, c.amount / f.base_amount).items():
            total[k] = round(total.get(k, 0.0) + v, 4)
    return total


def store_food(
    conn: Connection,
    f: FoodIn,
    *,
    source: str = "vitalocal",
    source_ref: str | None = None,
    source_data: dict | None = None,
    update: bool = False,
) -> tuple[dict | None, bool]:
    """Insert (or with `update`, replace) a food. Returns (food, created); (None, False) when an
    update finds no food. An insert with a known id or source_ref returns the existing food."""
    fid = f.id or uuid.uuid4()
    nutrients = _dish_nutrients(conn, fid, f.components) if f.components else f.nutrients
    params = {
        "id": fid,
        "name": f.name.strip() or "?",
        "brand": (f.brand or "").strip() or None,
        "barcode": f.barcode,
        "base_amount": f.base_amount,
        "base_unit": f.base_unit,
        "portions": json.dumps([p.model_dump() for p in f.portions]),
        "nutrients": json.dumps(nutrients),
        "source": source,
        "source_ref": source_ref,
        "source_data": json.dumps(source_data) if source_data is not None else None,
        "favorite": f.favorite,
        "archived": f.archived,
    }
    if update:
        row = conn.execute(
            text("""UPDATE food SET name = :name, brand = :brand, barcode = :barcode,
                        base_amount = :base_amount, base_unit = :base_unit,
                        portions = CAST(:portions AS jsonb), nutrients = CAST(:nutrients AS jsonb),
                        favorite = :favorite, archived = :archived, updated_at = now()
                    WHERE id = :id RETURNING id"""),
            params,
        ).first()
        if row is None:
            return None, False
        created = False
    else:
        row = conn.execute(
            text("""INSERT INTO food (id, name, brand, barcode, base_amount, base_unit, portions, nutrients,
                        source, source_ref, source_data, favorite, archived)
                    VALUES (:id, :name, :brand, :barcode, :base_amount, :base_unit, CAST(:portions AS jsonb),
                        CAST(:nutrients AS jsonb), :source, :source_ref, CAST(:source_data AS jsonb),
                        :favorite, :archived)
                    ON CONFLICT DO NOTHING RETURNING id"""),
            params,
        ).first()
        if row is None:  # same id, or the same OFF product / Waistline item
            existing = conn.execute(
                text("""SELECT id FROM food WHERE id = :id
                        OR (source = :source AND source_ref = :source_ref) LIMIT 1"""),
                params,
            ).scalar()
            return get_food(conn, existing), False
        created = True
    if f.components is not None:
        conn.execute(text("DELETE FROM food_component WHERE food_id = :id"), {"id": fid})
        if f.components:
            conn.execute(
                text("""INSERT INTO food_component (food_id, position, component_id, amount)
                        VALUES (:f, :p, :c, :a)"""),
                [{"f": fid, "p": i, "c": c.food_id, "a": c.amount} for i, c in enumerate(f.components)],
            )
    return get_food(conn, fid), created


