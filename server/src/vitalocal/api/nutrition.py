@router.get("/nutrition/{day}")
def nutrition_day(day: date, conn: Connection = CONN) -> dict:
    """The day's diary: meals with their entries and sums, day totals and the nutrient goals."""
    from vitalocal.api.goals import goals_of_day

    retired = waistline_retired_at(conn) is not None
    names = meal_names(conn)
    entries = [entry_out(r, retired) for r in entries_of_day(conn, day)]
    n_meals = max([len(names)] + [e["meal_index"] + 1 for e in entries if e["meal_index"] is not None])
    meals = [{"index": i, "name": _meal_name(names, i), "entries": []} for i in range(n_meals)]
    other = {"index": None, "name": "Ohne Mahlzeit", "entries": []}
    for e in entries:
        (meals[e["meal_index"]] if e["meal_index"] is not None else other)["entries"].append(e)
    if other["entries"]:
        meals.append(other)
    for m in meals:
        t = day_totals([e["nutrients"] for e in m["entries"]])
        m["totals"] = {k: t[k]["value"] for k in MAIN_KEYS}
    return {
        "day": day,
        "meals": meals,
        "entries": len(entries),
        "totals": day_totals([e["nutrients"] for e in entries]),
        "goals": [g for g in goals_of_day(conn, day) if g["metric"] != "nutrition.drinks"],
        "waistline_retired": retired,
    }


