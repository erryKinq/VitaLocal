@router.get("/foods/barcode/{code}")
def food_by_barcode(code: str, conn: Connection = CONN) -> dict:
    """The catalog's food with this barcode; else looked up at Open Food Facts and stored.

    404: unknown everywhere. 503: OFF not reachable (or switched off). 429: our OFF budget per
    minute is used up.
    """
    try:
        code = off.normalize_barcode(code)
    except ValueError as e:
        raise HTTPException(422, str(e)) from e
    local = conn.execute(
        text("""SELECT id FROM food WHERE ltrim(barcode, '0') = ltrim(:c, '0')
                ORDER BY archived, (source = 'vitalocal') DESC, updated_at DESC LIMIT 1"""),
        {"c": code},
    ).scalar()
    if local is not None:
        return {**get_food(conn, local), "found": "catalog"}
    draft = _off(off.product, code)
    if draft is None:
        raise HTTPException(404, f"barcode {code} is unknown, also at Open Food Facts")
    return {**_store_off(conn, draft), "found": "off"}


@router.get("/foods/online")
def search_online(
    q: str = Query(min_length=2, max_length=100), limit: int = Query(20, ge=1, le=50),
    conn: Connection = CONN,
) -> list[dict]:  # fmt: skip
    """Search Open Food Facts (on demand only). Hits are not stored; `food_id` marks products
    already in the catalog. Take one over with `POST /foods/online/{code}`."""
    hits = _off(off.search, q, limit)
    codes = [h["barcode"] for h in hits]
    known = dict(
        conn.execute(
            text("SELECT source_ref, id FROM food WHERE source = 'off' AND source_ref = ANY(:c)"),
            {"c": codes},
        ).all()
    )
    return [
        {**{k: v for k, v in h.items() if k != "source_data"}, "food_id": known.get(h["barcode"])}
        for h in hits
    ]


@router.post("/foods/online/{code}", status_code=status.HTTP_201_CREATED)
def take_over_online(code: str, response: Response, conn: Connection = CONN) -> dict:
    try:
        code = off.normalize_barcode(code)
    except ValueError as e:
        raise HTTPException(422, str(e)) from e
    existing = conn.execute(
        text("SELECT id FROM food WHERE source = 'off' AND source_ref = :c"), {"c": code}
    ).scalar()
    if existing is not None:
        response.status_code = status.HTTP_200_OK
        return get_food(conn, existing)
    draft = _off(off.product, code)
    if draft is None:
        raise HTTPException(404, f"barcode {code} is unknown at Open Food Facts")
    return _store_off(conn, draft)


def _off(fn, *args):
    try:
        return fn(*args)
    except off.OffRateLimited as e:
        raise HTTPException(429, str(e)) from e
    except off.OffUnavailable as e:
        raise HTTPException(503, str(e)) from e


def _store_off(conn: Connection, draft: dict) -> dict:
    f = FoodIn(
        name=draft["name"] or f"Produkt {draft['barcode']}",
        brand=draft["brand"],
        barcode=draft["barcode"],
        base_amount=draft["base_amount"],
        base_unit=draft["base_unit"],
        portions=draft["portions"],
        nutrients=draft["nutrients"],
    )
    food, _ = store_food(
        conn, f, source="off", source_ref=draft["source_ref"], source_data=draft["source_data"]
    )
    return food


@router.get("/foods/usage")
def food_usage(conn: Connection = CONN) -> dict[str, dict]:
    """Per logged food: how often, when last and with which amount (the next entry's suggestion).
    The catalog cache (`updated_since`) only changes with the food, this changes with every entry."""
    rows = conn.execute(
        text("""SELECT DISTINCT ON (food_id) food_id,
                       count(*) OVER (PARTITION BY food_id) AS uses,
                       coalesce(logged_at, day::timestamptz) AS last_used, amount, quantity
                FROM nutrition_entry WHERE food_id IS NOT NULL
                ORDER BY food_id, day DESC, created_at DESC, logged_at DESC NULLS LAST""")
    )
    return {
        str(r.food_id): {
            "count": r.uses,
            "last_used": r.last_used,
            "last_amount": r.amount,
            "last_quantity": r.quantity,
        }
        for r in rows
    }


