@router.post("/nutrition/copy")
def copy_entries(c: CopyIn, conn: Connection = CONN) -> dict:
    """Log earlier entries again ("like yesterday") on `day`, at the same local time of day.
    Idempotent through the new ids the client sends along."""
    tz = _tz()
    sources = {
        r.id: r
        for r in conn.execute(
            text(f"SELECT {ENTRY_COLS} FROM nutrition_entry WHERE uid = ANY(:ids)"),
            {"ids": [i.from_ for i in c.items]},
        )
    }
    if missing := [str(i.from_) for i in c.items if i.from_ not in sources]:
        raise HTTPException(422, f"unknown entries: {', '.join(missing)}")
    created = 0
    for i in c.items:
        s = sources[i.from_]
        clock = s.logged_at.astimezone(tz).time() if s.logged_at else time(12, 0)
        item = {
            k: getattr(s, k) for k in ("food_id", "item_type", "name", "brand", "amount", "unit", "quantity")
        }
        item["nutrients"] = s.nutrients
        mi = c.meal_index if c.meal_index is not None else (s.meal_index or 0)
        created += _insert_entry(
            conn, i.id, datetime.combine(c.day, clock, tzinfo=tz), mi, item, c.entered_via
        )
    retired = waistline_retired_at(conn) is not None
    rows = conn.execute(
        text(f"SELECT {ENTRY_COLS} FROM nutrition_entry WHERE uid = ANY(:ids) ORDER BY logged_at"),
        {"ids": [i.id for i in c.items]},
    )
    return {"created": created, "entries": [entry_out(r, retired) for r in rows]}


