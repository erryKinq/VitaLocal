@router.delete("/foods/{food_id}", status_code=status.HTTP_204_NO_CONTENT)
def delete_food(food_id: uuid.UUID, conn: Connection = CONN) -> Response:
    """Deleted when never used; otherwise archived (entries, dishes and templates keep referring to it)."""
    used = conn.execute(
        text("""SELECT EXISTS (SELECT 1 FROM nutrition_entry WHERE food_id = :id)
                    OR EXISTS (SELECT 1 FROM food_component WHERE component_id = :id)
                    OR EXISTS (SELECT 1 FROM meal_template_item WHERE food_id = :id)"""),
        {"id": food_id},
    ).scalar()
    if used:
        conn.execute(
            text("UPDATE food SET archived = true, updated_at = now() WHERE id = :id"), {"id": food_id}
        )
    else:
        conn.execute(text("DELETE FROM food WHERE id = :id"), {"id": food_id})
    return Response(status_code=status.HTTP_204_NO_CONTENT)


