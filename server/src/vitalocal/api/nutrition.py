@router.put("/nutrition/entries/{entry_id}")
def update_entry(entry_id: uuid.UUID, u: EntryUpdate, conn: Connection = CONN) -> dict:
    old = _get_entry(conn, entry_id)
    if old is None:
        raise HTTPException(404, "entry not found")
    retired = waistline_retired_at(conn) is not None
    if not editable(old.source, retired):
        raise HTTPException(409, "Waistline entries can be edited after the Waistline takeover")
    if u.nutrients is not None:
        item = _quick(u.name or old.name, u.nutrients, u.quantity)
    elif u.food_id is not None and u.food_id != old.food_id:
        item = _from_food(conn, u.food_id, u.amount, u.quantity)
    elif u.recompute and old.food_id is not None:
        item = _from_food(conn, old.food_id, u.amount or old.amount, u.quantity)
    else:
        # same food: scale the snapshot, so a changed food does not rewrite what was eaten
        amount = u.amount if old.amount is not None else None
        old_total = (old.amount or 1.0) * (old.quantity or 1.0)
        new_total = (amount or 1.0) * u.quantity
        item = {
            "food_id": old.food_id,
            "item_type": old.item_type,
            "name": u.name or old.name,
            "brand": old.brand,
            "amount": amount if amount is not None else old.amount,
            "unit": old.unit,
            "quantity": u.quantity,
            "nutrients": scaled(old.nutrients, new_total / old_total if old_total else 1.0),
        }
    conn.execute(
        text("""UPDATE nutrition_entry SET day = :day, meal_index = :mi, meal = :meal, logged_at = :at,
                    item_type = :item_type, food_id = :food_id, name = :name, brand = :brand,
                    amount = :amount, unit = :unit, quantity = :quantity,
                    nutrients = CAST(:nutrients AS jsonb), updated_at = now()
                WHERE uid = :uid"""),
        {
            **item,
            "nutrients": json.dumps(item["nutrients"]),
            "uid": entry_id,
            "day": u.logged_at.astimezone(_tz()).date(),
            "mi": u.meal_index,
            "meal": _meal_name(meal_names(conn), u.meal_index),
            "at": u.logged_at,
        },
    )
    return entry_out(_get_entry(conn, entry_id), retired)


