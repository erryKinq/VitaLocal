#!/bin/bash
# Builds the VitaLocal watch app (Connect IQ) for the Venu 4 into watch/bin/VitaLocal.prg and, when
# the phone is connected over adb, copies it to its Download folder (install: open it with
# Gadgetbridge). The server address and API token are compiled in from ../.env (Secrets.mc, not
# committed). Gadgetbridge must allow the server's host in the device's internet firewall.
#   VITALOCAL_WATCH_URL  server address the watch reaches through the phone (from ../.env), e.g.
#                        http://192.168.1.10:8000
#   VITALOCAL_API_TOKEN  from ../.env
#   WATCH_DEVICE         default venu445mm
set -euo pipefail
ROOT="$(cd "$(dirname "$0")" && pwd)"
CIQ="$HOME/Library/Application Support/Garmin/ConnectIQ"
KEY="$HOME/Library/Application Support/VitaLocal/connectiq_developer_key.der"
export JAVA_HOME="${JAVA_HOME:-/opt/homebrew/opt/openjdk@17/libexec/openjdk.jdk/Contents/Home}"
export PATH="$JAVA_HOME/bin:$PATH"
SDK="$(cat "$CIQ/current-sdk.cfg")"
[ -f "$KEY" ] || { echo "Developer key missing: $KEY"; exit 1; }

env_value() { grep -E "^$1=" "$ROOT/../.env" | tail -1 | cut -d= -f2- | sed -e 's/^["'\'']//' -e 's/["'\'']$//'; }
URL="${VITALOCAL_WATCH_URL:-$(env_value VITALOCAL_WATCH_URL || true)}"
[ -n "$URL" ] || { echo "VITALOCAL_WATCH_URL missing in .env"; exit 1; }
TOKEN="${VITALOCAL_API_TOKEN:-$(env_value VITALOCAL_API_TOKEN)}"
[ -n "$TOKEN" ] || { echo "VITALOCAL_API_TOKEN missing in .env"; exit 1; }

( umask 077
  printf '// Generated by build.sh – not committed.\nimport Toybox.Lang;\n(:background :glance)\nconst API_BASE = "%s";\n(:background :glance)\nconst API_TOKEN = "%s";\n' "${URL%/}" "$TOKEN" \
    > "$ROOT/source/Secrets.mc" )

mkdir -p "$ROOT/bin"
"$SDK/bin/monkeyc" -f "$ROOT/monkey.jungle" -d "${WATCH_DEVICE:-venu445mm}" -o "$ROOT/bin/VitaLocal.prg" -y "$KEY" -w
echo "Built $ROOT/bin/VitaLocal.prg for ${URL%/}"

PHONE=$(adb devices -l 2>/dev/null | awk '/model:Pixel_8a/ {print $1; exit}')
if [ -n "$PHONE" ]; then
  adb -s "$PHONE" push "$ROOT/bin/VitaLocal.prg" /sdcard/Download/VitaLocal.prg >/dev/null
  echo "Copied to the phone: Download/VitaLocal.prg (open it with Gadgetbridge to install)"
fi
